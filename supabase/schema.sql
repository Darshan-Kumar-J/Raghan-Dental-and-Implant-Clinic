-- Raghan Dental and Implant Care — Supabase PostgreSQL Schema
-- Run this SQL once in your Supabase Dashboard -> SQL Editor -> New Query

-- 1. Appointments Table
CREATE TABLE IF NOT EXISTS public.appointments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reference_code TEXT NOT NULL UNIQUE,
  treatment_id INTEGER NOT NULL,
  treatment_title TEXT NOT NULL,
  doctor_id INTEGER NOT NULL,
  doctor_name TEXT NOT NULL,
  appointment_date DATE NOT NULL,
  appointment_time TEXT NOT NULL,
  duration_minutes INTEGER NOT NULL DEFAULT 30,
  patient_name TEXT NOT NULL,
  patient_phone TEXT NOT NULL,
  patient_email TEXT NOT NULL DEFAULT '',
  patient_type TEXT NOT NULL DEFAULT 'first-time' CHECK (patient_type IN ('first-time', 'returning')),
  notes TEXT NOT NULL DEFAULT '',
  status TEXT NOT NULL DEFAULT 'Pending' CHECK (status IN ('Pending', 'Confirmed', 'Completed', 'Cancelled', 'Rescheduled', 'No-show')),
  payment_status TEXT NOT NULL DEFAULT 'Pay at Clinic' CHECK (payment_status IN ('Not Required', 'Pay at Clinic', 'Pending Payment', 'Paid')),
  payment_amount_inr INTEGER NOT NULL DEFAULT 0,
  razorpay_order_id TEXT NOT NULL DEFAULT '',
  razorpay_payment_id TEXT NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 2. Database-level Double-Booking Prevention
CREATE UNIQUE INDEX IF NOT EXISTS idx_active_booking_slot
  ON public.appointments (doctor_id, appointment_date, appointment_time)
  WHERE status NOT IN ('Cancelled', 'Rescheduled');

-- 3. Contact Enquiries Table
CREATE TABLE IF NOT EXISTS public.contact_enquiries (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  phone TEXT NOT NULL,
  email TEXT NOT NULL DEFAULT '',
  subject TEXT NOT NULL DEFAULT 'General Enquiry',
  message TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'New' CHECK (status IN ('New', 'Reviewed', 'Responded')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 4. Row-Level Security (Protect Patient PII from Public Read Access)
ALTER TABLE public.appointments ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.contact_enquiries ENABLE ROW LEVEL SECURITY;

-- Allow website visitors to insert new appointment requests (no SELECT access to patient PII)
DROP POLICY IF EXISTS "Allow public booking insert" ON public.appointments;
CREATE POLICY "Allow public booking insert"
  ON public.appointments
  FOR INSERT
  TO anon, authenticated
  WITH CHECK (
    char_length(trim(patient_name)) >= 2
    AND char_length(trim(patient_phone)) >= 10
    AND status IN ('Pending', 'Confirmed')
  );

-- Allow website visitors to insert contact enquiries (no SELECT access to PII)
DROP POLICY IF EXISTS "Allow public enquiry insert" ON public.contact_enquiries;
CREATE POLICY "Allow public enquiry insert"
  ON public.contact_enquiries
  FOR INSERT
  TO anon, authenticated
  WITH CHECK (
    char_length(trim(name)) >= 2
    AND char_length(trim(phone)) >= 10
    AND char_length(trim(message)) >= 5
  );

-- 5. Safe Slot Availability RPC (Returns ONLY busy time & duration, zero patient PII)
CREATE OR REPLACE FUNCTION public.get_busy_slots(p_date DATE, p_doctor_id INTEGER)
RETURNS TABLE (appointment_time TEXT, duration_minutes INTEGER)
LANGUAGE SQL
SECURITY DEFINER
SET search_path = public
AS $$
  SELECT a.appointment_time, a.duration_minutes
  FROM public.appointments a
  WHERE a.appointment_date = p_date
    AND a.doctor_id = p_doctor_id
    AND a.status NOT IN ('Cancelled', 'Rescheduled');
$$;

GRANT EXECUTE ON FUNCTION public.get_busy_slots(DATE, INTEGER) TO anon, authenticated;
